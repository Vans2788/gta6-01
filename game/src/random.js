// Deterministic randomness (mulberry32). A ?seed=N run builds the same city,
// the same traffic and the same pedestrians every time, which is what makes
// the staged screenshots reproducible. Pure functions, no shared state.
// The increment 0x6d2b79f5 and the 61 multiplier are the classic mulberry32
// constants: cheap, fast, and evenly spread across the 32-bit range.
export function createRandom(seed) {
  let state = seed >>> 0;
  return {
    next() {
      state |= 0;
      state = (state + 0x6d2b79f5) | 0;
      let mixed = Math.imul(state ^ (state >>> 15), 1 | state);
      mixed = (mixed + Math.imul(mixed ^ (mixed >>> 7), 61 | mixed)) ^ mixed;
      return ((mixed ^ (mixed >>> 14)) >>> 0) / 4294967296;
    },
    range(min, max) {
      return min + this.next() * (max - min);
    },
    int(min, max) {
      return Math.floor(this.range(min, max + 1));
    },
    pick(list) {
      return list[Math.floor(this.next() * list.length)];
    },
    chance(p) {
      return this.next() < p;
    },
  };
}
